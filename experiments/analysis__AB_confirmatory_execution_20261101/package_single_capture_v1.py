"""Copy reviewed technical evidence, never weights or unrelated caches."""
from pathlib import Path
import hashlib,json,shutil

ROOT=Path(__file__).resolve().parents[2]
STAGE=ROOT/'analysis/AB_confirmatory_execution_20261101/single_capture_v1'
DEST=Path('C:/Users/rafal/Downloads/Tor_A_2026-10-31/dowody/AB_confirmatory_20261101/single_capture_v1')


def sha(p):
    with Path(p).open('rb') as f:return hashlib.file_digest(f,'sha256').hexdigest()


def main():
    review=json.loads((STAGE/'completion_review_v1.json').read_text())
    if review['verdict']!='approved':raise ValueError('completion not approved')
    if DEST.exists():raise ValueError('version destination already exists; never overwrite')
    pairs=[]
    for p in STAGE.rglob('*'):
        if p.is_file() and '__pycache__' not in p.parts and p.suffix!='.pyc':
            pairs.append((p,Path('stage')/p.relative_to(STAGE)))
    for name in ['__init__.py','single_capture.py','test_single_capture.py','prepare_single.py','prepare.py']:
        pairs.append((ROOT/'ab_confirmatory_20261101'/name,Path('src/ab_confirmatory_20261101')/name))
    for p in (ROOT/'research_checks').glob('*.py'):
        pairs.append((p,Path('src/research_checks')/p.name))
    for name in ['main.pdf','main.tex']:
        pairs.append((ROOT/'papers/AB_v4_20261101/A'/name,Path('article_context')/name))
    pairs.append((ROOT/'papers/AB_v4_20261101/references.bib',Path('article_context/references.bib')))
    pairs.append((ROOT/'plans/AB_ZASADY_ODDZIELNYCH_PAKIETOW_2026-11-01.md',Path('PACKAGING_CONVENTION.md')))
    manifest={}
    for source,relative in pairs:
        target=DEST/relative;target.parent.mkdir(parents=True,exist_ok=True)
        shutil.copy2(source,target)
        h=sha(source)
        if sha(target)!=h:raise ValueError('copy mismatch '+str(relative))
        manifest[relative.as_posix()]=dict(bytes=target.stat().st_size,sha256=h,source=str(source))
    readme='''# Reviewed technical capture package — A prospective preparation\n\nThis version preserves exactly one natural Gemma1B capture and its genuine pre-run/completion reviews, raw vectors, accounting, cache-replay evidence and source/model identities. It supports a technical implementation record only; no A1–A3/B1–B3 result, fitted sample, sensitivity or transfer claim. The article in article_context is unchanged v4 context and does not present this capture as new confirmation. No historical article files were overwritten.\n\nMap: technical claim/requested hook capture -> stage/REPORT_COMPLETION_v1.md and stage/run/completed.json; raw same-forward checks -> stage/run/cache/*.json; exact1forward and cached replay -> stage/run/attempt.json, stage/run/computed.json, stage/actual_cached_replay_v1.json; accepted scope -> stage/PROTOCOL.md, stage/pre_run_review_v1.json, stage/completion_review_v1.json. All limitations and negative-gate status in the reports remain. The broader statistical calibration is incomplete and is not admitted by this package.\n\nOffline source tests: from src run python -m ab_confirmatory_20261101.test_single_capture (random model/mock only). Original native execution remains in the main lab; weights are deliberately omitted. Model files/libraries and the historical data underlying the contextual article remain external dependencies, so this narrow package is not a self-contained reproduction of every article result. The exact selected prompt/tokens and raw record are present. Do not run a pretrained remeasurement from this copy.\n\nMANIFEST.json maps relative files to their lab source, byte count and SHA256; all copied bytes were verified. This record is shared preparation evidence, not an additional independent replication.\n'''
    (DEST/'README.md').write_text(readme,encoding='utf-8')
    manifest['README.md']=dict(bytes=(DEST/'README.md').stat().st_size,sha256=sha(DEST/'README.md'),source='generated by '+str(Path(__file__)))
    (DEST/'MANIFEST.json').write_text(json.dumps(dict(files=manifest,scope='one reviewed technical capture only',
        completion_snapshot=review['snapshot_sha256']),indent=2),encoding='utf-8')
    receipt=dict(destination=str(DEST),files=len(manifest),manifest_sha256=sha(DEST/'MANIFEST.json'),
                 bytes_verified=True,completion_snapshot=review['snapshot_sha256'])
    (ROOT/'analysis/AB_confirmatory_execution_20261101/single_capture_delivery_v1.json').write_text(json.dumps(receipt,indent=2))
    print(json.dumps(receipt))


if __name__=='__main__':main()
