"""Read-only independent archive byte/provenance audit. No scientific execution."""
import hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[3]
BASE=ROOT/'analysis/AB_confirmatory_execution_20261101'
OUT=Path(__file__).resolve().parent
def sha(p):
    with p.open('rb') as stream:return hashlib.file_digest(stream,'sha256').hexdigest()
def read(p):return json.loads(p.read_text(encoding='utf-8-sig'))
def audit(receipt_name,prior=None):
    receipt=read(BASE/receipt_name);dest=Path(receipt['destination']);manifest=dest/'MANIFEST.json'
    assert sha(manifest)==receipt['manifest_sha256'],'manifest hash'
    m=read(manifest);index={};total=0;generated=[];mismatches=[]
    for name,entry in m['files'].items():
        p=(dest/name).resolve();assert p.is_relative_to(dest),'escaped member'
        assert p.stat().st_size==entry['bytes'] and sha(p)==entry['sha256'],name
        total+=entry['bytes'];source=entry['source']
        if source.startswith('generated by '):generated.append(name)
        else:
            source_path=Path(source);assert source_path.is_file(),source
            if sha(source_path)!=entry['sha256']:mismatches.append(dict(member=name,source=source))
            index[str(source_path.resolve())]=dict(member=name,sha256=entry['sha256'],bytes=entry['bytes'])
    historical=[]
    for mismatch in mismatches:
        source=Path(mismatch['source']);relative=source.relative_to(ROOT).as_posix()
        expected=m['files'][mismatch['member']]['sha256']
        evidence=[]
        for snap in dest.glob('stage/*snapshot*.json'):
            if read(snap).get('payload',{}).get('files',{}).get(relative)==expected:evidence.append(str(snap))
        assert evidence,repr(mismatch)
        historical.append(dict(**mismatch,archived_sha256=expected,accepted_historical_snapshots=evidence))
    expected_count=receipt.get('files',receipt.get('new_files'));expected_bytes=receipt.get('copied_bytes',receipt.get('new_bytes'))
    assert len(m['files'])==expected_count and total==expected_bytes,'counts'
    if prior:
        assert m['prior_manifest_sha256']==prior['manifest_sha256']==receipt['prior_manifest_sha256']
        for source,entry in m['shared_prior_members'].items():
            previous=prior['source_index'][str(Path(entry['source']).resolve())]
            assert previous['sha256']==entry['sha256'] and previous['bytes']==entry['bytes']
            assert (dest/entry['package_relative_path']).resolve()==Path(prior['destination'])/previous['member']
        assert len(m['shared_prior_members'])==receipt['shared_files']
    result=dict(destination=str(dest),manifest_sha256=receipt['manifest_sha256'],files_verified=len(m['files']),bytes_verified=total,shared_prior_verified=len(m.get('shared_prior_members',{})),source_index=index,generated_members=generated,all_destination_hashes_sizes_match=True,all_nongenerated_sources_match=not historical,historical_source_deviations=historical)
    return result,m

def main():
    first,fm=audit('A_fit_delivery_v1.json')
    fit_review=read(BASE/'A_fit_primary_v1/completion_review_sol/completion_review_v2.json')
    assert fit_review['verdict']=='approved' and fit_review['independent'] and fit_review['snapshot_sha256']==fm['completion_snapshot']
    second,sm=audit('A_pilot_selector_delivery_v2.json',first)
    expected=[]
    for directory in ['A_pilot_ready_v1','A_selector_ready_v1']:
        review=read(BASE/directory/'completion_review_sol_v1.json');assert review['verdict']=='approved' and review['independent']
        expected.append(review['snapshot_sha256'])
    assert sm['completion_snapshots']==expected
    text=(Path(second['destination'])/'README.md').read_text(encoding='utf-8')
    assert all(term in text for term in ['ORIGINAL frozen selector','Later fixed-resource A v7 TEST','INFEASIBLE_UNDER_FROZEN_CAP','No fit/model/bootstrap campaign was repeated'])
    (OUT/'a_delivery_verified_index_v1.json').write_text(json.dumps(dict(fit=first,pilot_selector=second),indent=2)+'\n',encoding='utf-8')
    for name,result,scope in [('A_fit_delivery_review_sol_v1.json',first,'Mechanical FIT archive delivery only; original independently accepted FIT, no PILOT/TEST/inference approval.'),('A_pilot_selector_delivery_review_sol_v2.json',second,'Historical accepted PILOT and negative original selector archive only; later resource-v7 TEST excluded, no 80% power claim.')]:
        record=dict(reviewer_id='/root/sol_parallel_acceptance',independent=True,verdict='approved',scope=scope,manifest_sha256=result['manifest_sha256'],files_verified=result['files_verified'],bytes_verified=result['bytes_verified'],shared_prior_verified=result['shared_prior_verified'],all_destination_hashes_sizes_match=True,all_nongenerated_sources_match=result['all_nongenerated_sources_match'],historical_source_deviations=result['historical_source_deviations'],generated_members=result['generated_members'],limitations='Mechanical delivery review only; prior scientific acceptance reused. Pretrained weights omitted with identities retained. No experiment, fitting, bootstrap, Monte Carlo or model calls repeated. Original laboratory paths require provenance mapping. Independent FIT archive delivery review is issued now; historical wording about prior archive review refers to scientific acceptance until this receipt.',evidence='sol_parallel_acceptance/a_delivery_verified_index_v1.json')
        (BASE/name).write_text(json.dumps(record,indent=2)+'\n',encoding='utf-8')
    print(json.dumps({key:{k:v for k,v in value.items() if k!='source_index'} for key,value in [('fit',first),('pilot_selector',second)]}))
if __name__=='__main__':main()
