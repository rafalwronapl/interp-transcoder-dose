"""Copy accepted B FIT evidence and verify bytes; never run a model or refit."""
from pathlib import Path
import hashlib, json, shutil

ROOT=Path(__file__).resolve().parents[2]
BASE=ROOT/'analysis/AB_confirmatory_execution_20261101'
STAGE=BASE/'B_fit_reference_recovery_v2'
DEST=Path('C:/Users/rafal/Downloads/Tor_B_2026-10-31/dowody/AB_confirmatory_20261101/B_fit_composite_v1')

def sha(p):
    with p.open('rb') as f: return hashlib.file_digest(f,'sha256').hexdigest()

def main():
    review=json.loads((STAGE/'completion_review_astra_v1.json').read_text())
    if review['verdict']!='approved': raise ValueError('No independent acceptance')
    if DEST.exists(): raise ValueError('Existing archive must never be overwritten')
    snap=json.loads((STAGE/'completion_snapshot_v1.json').read_text())
    sources={ROOT/name: Path('lab')/name for name in snap['payload']['files']}
    for name in ['B_fit_primary_v1','B_reference_unfused_v1','B_fit_reference_recovery_v2']:
        for p in (BASE/name).rglob('*'):
            if p.is_file() and '__pycache__' not in p.parts and p.suffix!='.pyc':
                sources[p]=Path('lab')/p.relative_to(ROOT)
    for name in ['main.tex','main.pdf']:
        p=ROOT/'papers/AB_v4_20261101/B'/name
        if p.exists(): sources[p]=Path('article_context')/name
    p=ROOT/'papers/AB_v4_20261101/references.bib'
    sources[p]=Path('article_context/references.bib')
    manifest={}; omitted={}
    for source,relative in sorted(sources.items()):
        if source.suffix.lower() in {'.safetensors','.bin','.pt','.pth','.ckpt'}:
            omitted[source.relative_to(ROOT).as_posix()]=dict(reason='pretrained weights omitted',sha256=sha(source))
            continue
        expected=snap['payload']['files'].get(source.relative_to(ROOT).as_posix())
        h=sha(source)
        if expected and expected!=h: raise ValueError('Accepted source changed: '+str(source))
        target=DEST/relative
        target.parent.mkdir(parents=True,exist_ok=True)
        shutil.copy2(source,target)
        if sha(target)!=h: raise ValueError('Copied bytes mismatch')
        manifest[relative.as_posix()]=dict(source=str(source),sha256=h,bytes=target.stat().st_size)
    readme='''# Accepted B FIT acquisition and vector fitting

This archive contains 128 natural FIT records from 32 name pairs, frozen direction
and 36 fixed-lambda vector baseline cells. It does not contain PILOT/TEST or a B1–B3
hypothesis result. All controls, the original serialization failure, failed fused
reference comparison, four new unfused references and narrow recovery travel together.
The original 64 logical operations were reused, never recomputed. Combined cost is
1864 forward and 4 backward operations: 152 full transformer, 1692 local native,
8 JVP and 12 TC/reference forward operations. Both qualification gates passed under
the independently reviewed reference amendment with unchanged numerical thresholds.

Authoritative acceptance and report are in
lab/analysis/AB_confirmatory_execution_20261101/B_fit_reference_recovery_v2/.
completion_review_astra_v1.json binds snapshot d0d3ef007a9c3e9741729ccb7c04f007021ac8590f992dabd6d92d48164585f4.
The lab-relative hierarchy preserves raw/cache/ledger/source provenance. Historical
failed receipts are preserved and do not replace the authoritative completion review.
The contextual article is unchanged and does not present this FIT as confirmation.

MANIFEST.json records source, size and SHA256 for every copied file. Copied bytes
were verified. Pretrained LLM/TC weights are excluded with identity hashes retained;
learned FIT results and natural cached states are included. Library/environment
identities remain in accepted snapshots. Do not run archived workers merely to
review these results. This is a FIT-stage evidence archive, not a self-contained
reproduction of every historical claim in the contextual article.
'''
    (DEST/'README.md').write_text(readme,encoding='utf-8')
    manifest['README.md']=dict(source='generated by '+str(Path(__file__)),sha256=sha(DEST/'README.md'),bytes=(DEST/'README.md').stat().st_size)
    (DEST/'MANIFEST.json').write_text(json.dumps(dict(files=manifest,omitted=omitted,completion_snapshot=review['snapshot_sha256'],scope='B FIT only; no PILOT/TEST/hypothesis result'),indent=2),encoding='utf-8')
    receipt=dict(destination=str(DEST),files=len(manifest),copied_bytes=sum(x['bytes'] for x in manifest.values()),
        manifest_sha256=sha(DEST/'MANIFEST.json'),all_copied_bytes_verified=True,completion_snapshot=review['snapshot_sha256'],omitted_weights=len(omitted))
    (BASE/'B_fit_delivery_v1.json').write_text(json.dumps(receipt,indent=2),encoding='utf-8')
    print(json.dumps(receipt))

if __name__=='__main__': main()
