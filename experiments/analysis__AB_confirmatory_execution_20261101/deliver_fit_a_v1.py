"""Mechanical delivery of accepted FIT evidence; no research computation."""
from pathlib import Path
import hashlib,json,shutil

ROOT=Path(__file__).resolve().parents[2]
STAGE=ROOT/'analysis/AB_confirmatory_execution_20261101/A_fit_primary_v1'
DEST=Path('C:/Users/rafal/Downloads/Tor_A_2026-10-31/dowody/AB_confirmatory_20261101/A_fit_primary_v1')


def sha(p):
    with Path(p).open('rb') as f:return hashlib.file_digest(f,'sha256').hexdigest()


def main():
    review=json.loads((STAGE/'completion_review_sol/completion_review_v2.json').read_text())
    if review['verdict']!='approved':raise ValueError('completion not approved')
    if DEST.exists():raise ValueError('version destination exists, never overwrite')
    pairs=[]
    for source in STAGE.rglob('*'):
        if source.is_file() and '__pycache__' not in source.parts and source.suffix!='.pyc':
            pairs.append((source,Path('stage')/source.relative_to(STAGE)))
    imported=json.loads((STAGE/'import_manifest.json').read_text())['files']
    for name in imported:pairs.append((ROOT/name,Path('upstream')/name))
    for name in ['__init__.py','worker_a.py','native.py','fitting.py','runtime.py','prepare.py','prepare_fit_a.py','schedule_a.py',
                 'test_worker_a.py','test_native.py','test_runtime.py','test_fitting.py']:
        pairs.append((ROOT/'ab_confirmatory_20261101'/name,Path('src/ab_confirmatory_20261101')/name))
    for source in (ROOT/'research_checks').glob('*.py'):pairs.append((source,Path('src/research_checks')/source.name))
    for name in ['main.pdf','main.tex']:pairs.append((ROOT/'papers/AB_v4_20261101/A'/name,Path('article_context')/name))
    pairs.append((ROOT/'papers/AB_v4_20261101/references.bib',Path('article_context/references.bib')))
    manifest={}
    for source,relative in pairs:
        target=DEST/relative;target.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(source,target)
        h=sha(source)
        if sha(target)!=h:raise ValueError('copy hash mismatch '+str(relative))
        manifest[relative.as_posix()]=dict(bytes=target.stat().st_size,sha256=h,source=str(source))
    text='''# A primary r0 FIT evidence — accepted stage\n\nThis version preserves448FIT records,one reused upstream capture,all technical controls,477newfull+5localsuffix accounting,frozenP/U and actual zero-load/zero-call cached replay. No PILOT/TEST or A1–A3result. The contextual articlev4 is unchanged and does not present this FIT as new confirmation. No prior delivery was overwritten.\n\nClaim map: acquisition/fitting scope -> stage/PROTOCOL.md and REPORT_COMPLETION_v1.md; actual frozen arrays -> stage/run/FIT_r0.json; native records -> stage/run/cache plus upstream single_capture rawcompleted; control evidence -> stage/run/controls.json and relatedcache; counts/replay -> fit_summary,ledger,operations,actual_cached_replay; genuine acceptance -> stage/completion_review_sol/completion_review_v2.json and canonicalverify. Superseded v1review schemafailure is retained; v2is authoritative. All controls and limitations travel with the data.\n\nMANIFEST.json maps every copied file to its original lab source,SHA256 and size; copied bytes were verified. Upstream imports required for the448record audit are included. Weights and unrelated caches are omitted. Environment/library identities remain in snapshots; native execution needs the original pinned weights and must not be rerun merely for review. Offline raw checks need no new model calls. Original labpaths in archived scripts can be mapped through this manifest. The package is a FIT-stage archive,not a self-contained reproduction of every historical claim in the contextual article.\n\nPrimaryr0 is predesignated; the15additionalFIT cohorts and statisticalcalibration/PILOT/TEST remain separately gated. No readout-outcome selection or automatic inference approval follows from successful fitting.\n'''
    (DEST/'README.md').write_text(text,encoding='utf-8')
    manifest['README.md']=dict(bytes=(DEST/'README.md').stat().st_size,sha256=sha(DEST/'README.md'),source='generated by '+str(Path(__file__)))
    (DEST/'MANIFEST.json').write_text(json.dumps(dict(files=manifest,completion_snapshot=review['snapshot_sha256'],
      scope='primaryr0FITonly;noPILOT/TEST/hypothesisresult'),indent=2),encoding='utf-8')
    receipt=dict(destination=str(DEST),files=len(manifest),copied_bytes=sum(v['bytes'] for v in manifest.values()),
      manifest_sha256=sha(DEST/'MANIFEST.json'),all_copied_bytes_verified=True,completion_snapshot=review['snapshot_sha256'])
    (STAGE.parent/'A_fit_delivery_v1.json').write_text(json.dumps(receipt,indent=2));print(json.dumps(receipt))


if __name__=='__main__':main()
