"""Deliver new accepted tail evidence; reuse already delivered shared FIT files."""
from pathlib import Path
import json,hashlib,shutil,os
ROOT=Path(__file__).resolve().parents[2]
BASE=ROOT/'analysis/AB_confirmatory_execution_20261101'
STAGE=BASE/'B_tail_qualification_v1'
PARENT=Path('C:/Users/rafal/Downloads/Tor_B_2026-10-31/dowody/AB_confirmatory_20261101')
DEST=PARENT/'B_tail_qualification_v1'
PRIOR=PARENT/'B_fit_composite_v1'
def read(p):return json.loads(p.read_text(encoding='utf-8-sig'))
def sha(p):
    with p.open('rb') as f:return hashlib.file_digest(f,'sha256').hexdigest()
def main():
    review=read(STAGE/'completion_review_astra_v1.json')
    if review['verdict']!='approved' or DEST.exists():raise ValueError('Acceptance required and destination must be new')
    prior_receipt=read(BASE/'B_fit_delivery_v1.json')
    if sha(PRIOR/'MANIFEST.json')!=prior_receipt['manifest_sha256']:raise ValueError('Prior delivered manifest changed')
    prior=read(PRIOR/'MANIFEST.json')['files']
    index={Path(v['source']):(k,v) for k,v in prior.items() if v['source'].startswith(str(ROOT))}
    files=dict(read(STAGE/'completion_snapshot_v1.json')['payload']['files'])
    for p in STAGE.rglob('*'):
        if p.is_file() and '__pycache__' not in p.parts and p.suffix!='.pyc':files[p.relative_to(ROOT).as_posix()]=sha(p)
    copied={};shared={};omitted={}
    for name,expected in sorted(files.items()):
        source=ROOT/name
        if source.suffix.lower() in {'.safetensors','.bin','.pt','.pth','.ckpt'}:
            omitted[name]=dict(sha256=expected,reason='pretrained weights omitted; accepted identity retained')
            continue
        if source in index and index[source][1]['sha256']==expected:
            old_name,old=index[source];existing=PRIOR/old_name
            if not existing.is_file() or existing.stat().st_size!=old['bytes']:raise ValueError('Shared delivered file missing')
            shared[name]=dict(package_relative_path=os.path.relpath(existing,DEST).replace('\\','/'),sha256=expected,bytes=old['bytes'],source=str(source))
            continue
        if sha(source)!=expected:raise ValueError('Accepted source changed: '+name)
        relative=Path('lab')/name;target=DEST/relative;target.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(source,target)
        if sha(target)!=expected:raise ValueError('Copied bytes mismatch')
        copied[relative.as_posix()]=dict(source=str(source),sha256=expected,bytes=target.stat().st_size)
    text='''# Accepted B native-tail technical qualification

Four previously unused FIT-transfer recipients and16full/projected dose cells qualified
the exact dynamic native tail at Gemma270M layer15. Saved full/tail finite-margin
differences and natural gradient diagnostics are0. Maximum native/captured branch
relative discrepancy is4.9189e-7. Cost152F/8B:56full,52tail,16local native,20TC,8JVP.
This is tiny-set operator qualification, not PILOT/TEST or B1–B3 support. The separate
failed B precision-method gates remain in force and are not waived by this result.

Raw controls/cache/results/ledger, code, protocol and genuine completion acceptance
are archived under lab/analysis/AB_confirmatory_execution_20261101/B_tail_qualification_v1/.
The accepted completion snapshot is b3a3bd6a0bf4a0a673c6185d18c19a2f52ca7501749f1ff7acf6e4d5390bc152.
MANIFEST.json distinguishes newly copied files from shared members of the already
reviewed ../B_fit_composite_v1 archive. Both neighboring packages are required for
the full upstream closure; shared FIT raw records and old failures are not duplicated.
Shared provenance is not an independent replication. Prior manifest identity is bound.
All newly copied bytes were verified; no model/refit/bootstrap or old capture rerun.
Pretrained weights are omitted with accepted hashes retained. Original lab paths can
be resolved through provenance. Archived workers must not be rerun merely for review.
'''
    (DEST/'README.md').write_text(text,encoding='utf-8')
    copied['README.md']=dict(source='generated by '+str(Path(__file__)),sha256=sha(DEST/'README.md'),bytes=(DEST/'README.md').stat().st_size)
    (DEST/'MANIFEST.json').write_text(json.dumps(dict(files=copied,shared_prior_members=shared,omitted=omitted,
        prior_manifest_sha256=prior_receipt['manifest_sha256'],completion_snapshot=review['snapshot_sha256']),indent=2),encoding='utf-8')
    receipt=dict(destination=str(DEST),new_files=len(copied),new_bytes=sum(v['bytes'] for v in copied.values()),shared_files=len(shared),
        manifest_sha256=sha(DEST/'MANIFEST.json'),all_new_bytes_verified=True,prior_manifest_sha256=prior_receipt['manifest_sha256'])
    (BASE/'B_tail_delivery_v1.json').write_text(json.dumps(receipt,indent=2),encoding='utf-8');print(json.dumps(receipt))
if __name__=='__main__':main()
